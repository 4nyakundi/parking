<?php
declare(strict_types=1);
if (PHP_SAPI !== 'cli') exit;
require_once __DIR__ . '/../includes/databank.php';
$db = get_db();
$db->exec('CREATE TEMPORARY TABLE databank_profile_template LIKE registered_vehicles');
$db->exec('CREATE TEMPORARY TABLE registered_vehicles LIKE databank_profile_template');
$db->exec('CREATE TEMPORARY TABLE databank_session_template LIKE parking_sessions');
$db->exec('CREATE TEMPORARY TABLE parking_sessions LIKE databank_session_template');
function check(bool $ok, string $message): void { if (!$ok) throw new RuntimeException($message); echo "PASS: {$message}\n"; }
$db->prepare('INSERT INTO registered_vehicles (plate_number, owner_name, phone, category) VALUES (?, ?, ?, ?)')->execute(['KDA123A','Vehicle Owner','254711111111','vip']);
$add=$db->prepare('INSERT INTO parking_sessions (ticket_id,plate_number,driver_name,driver_phone,destination,entry_time,status,entry_method) VALUES (?,?,?,?,?,?,?,"manual")');
$add->execute(['TEST-1','KDA123A','Zara','254722222222','Shop Z','2026-01-01 10:00:00','COMPLETED']);
$add->execute(['TEST-2','KDA123A','Alice','254733333333','Shop A','2026-01-02 10:00:00','COMPLETED']); $latest=(int)$db->lastInsertId();
$add->execute(['TEST-CANCEL','KDA123A','Cancelled','254744444444','Cancelled Shop','2026-01-03 10:00:00','CANCELLED']);
$p=DataBank::lookup('KDA 123A');
check($p['driver_name']==='Alice' && $p['driver_phone']==='254733333333' && $p['default_destination']==='Shop A','latest details come from one chronological visit, not MAX text or owner');
check($p['visit_count']===2 && !$p['is_frequent'],'cancelled sessions do not inflate visit totals');
DataBank::recordVisit('KDA123A','','','',$latest,true,1);
DataBank::recordVisit('KDA123A','','','',$latest,true,1);
$r=$db->query('SELECT * FROM registered_vehicles WHERE plate_number="KDA123A"')->fetch();
check((int)$r['visit_count']===2,'retrying profile save does not count the visit twice');
check($r['owner_name']==='Vehicle Owner' && $r['phone']==='254711111111' && $r['category']==='vip','confirmed driver never overwrites owner, owner phone, or category');
$add->execute(['TEST-3','KDA123A','Different Driver','254755555555','Shop B','2026-01-04 10:00:00','ACTIVE']); $third=(int)$db->lastInsertId();
DataBank::recordVisit('KDA123A','','','',$third,false,1);
$p=DataBank::lookup('KDA123A');
check($p['driver_name']==='Alice' && $p['visit_count']===3 && $p['is_frequent'],'different driver can be recorded without replacing the reusable profile');
DataBank::recordVisit('KDA123A','','','',$third,true,1);
DataBank::recordVisit('KDA123A','','','',$latest,true,1);
check(DataBank::lookup('KDA123A')['driver_name']==='Different Driver','late older callbacks cannot overwrite the latest confirmed driver');
$db->exec('UPDATE registered_vehicles SET profile_archived=1 WHERE plate_number="KDA123A"');
$p=DataBank::lookup('KDA123A');
check($p['driver_name']==='' && $p['driver_phone']==='' && $p['skip_details']===false,'archived profiles do not offer personal details or automatic admission');
$db->exec('UPDATE registered_vehicles SET profile_archived=0, driver_name="", driver_phone="", default_destination="", profile_reset_at="2026-12-01" WHERE plate_number="KDA123A"');
check(DataBank::lookup('KDA123A')['has_bank_profile']===false,'identity reset prevents reuse of details from old visits');
check((int)$db->query('SELECT COUNT(*) FROM parking_sessions')->fetchColumn()===4,'all historical visit rows remain intact');
$add->execute(['TEST-NEW','KDB456B','New Driver','254766666666','Shop C','2026-01-05 10:00:00','ACTIVE']); $new=(int)$db->lastInsertId();
DataBank::recordVisit('KDB456B','','','',$new,false,1);
check(DataBank::lookup('KDB456B')['has_bank_profile']===false,'unremembered first visit does not become a reusable identity');
echo "Data Bank regression checks passed using temporary tables only.\n";
